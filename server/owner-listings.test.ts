import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {publicViewingListing,publicViewingListings} from './public-viewing.js';
import releaseJson from './public-viewing-release.json';
import type { ViewingListing } from '../src/viewing-types.js';
// 悦港 starts with an empty third-party release; keep the listing type for these legacy checks.
const release = releaseJson as unknown as { version: number; release: string; listings: ViewingListing[]; media: Record<string, { key: string; sha256: string; bytes: number; contentType: string }> };
import {ownerListingsComBundle} from '../scripts/com-owner-listings.mjs';
import {saleListingComBundle} from '../scripts/com-sale-listing.mjs';
import {leadSchema} from './schema.js';

test('Upper Coomera is a for-sale listing reusing the existing photos, not a rental or a sold record',()=>{
 const own=publicViewingListing('reference-20261031001');assert.ok(own);
 assert.equal(own.kind,'sale');
 assert.equal(publicViewingListings('sale').map(l=>l.id).join(),own.id);
 assert.equal(publicViewingListings('rent').some(l=>l.id===own.id),false);
 assert.deepEqual(publicViewingListings('sold'),release.listings.filter(l=>l.kind==='sold'));
 assert.deepEqual(publicViewingListings('rent'),release.listings.filter(l=>l.kind==='rent'&&l.availabilityStatus==='available'));
 assert.equal(own.priceDisplay.zh,'A$720,000');assert.equal(own.priceBasis,'asking_sale');
 assert.equal(own.beds,3);assert.equal(own.baths,1);assert.equal(own.cars,null);
 assert.equal(own.suburb,'Upper Coomera');assert.equal(own.city,'Gold Coast');assert.equal(own.postcode,'4209');
 const facts=(own.features??[]).map(f=>f.zh).join('\n');
 assert.match(facts,/因资金周转需要诚意出售/);
 assert.match(facts,/三间卧室/);
 assert.match(facts,/开放式客厅、餐厅与厨房/);
 assert.match(facts,/浴缸和淋浴/);
 assert.match(facts,/前院及有顶露台/);
 assert.equal(own.soldPrice,null);assert.equal(own.soldDate,null);
 assert.equal(own.geo,null);assert.equal(own.mapUrl,'');assert.equal(own.availableDate,null);
 assert.equal(own.rooms.length,11);assert.ok(own.rooms.every(r=>r.videoUrl===null&&/^\/uploads\/[a-f0-9-]{36}\.(?:png|webp)$/.test(r.photoUrl)));
 assert.doesNotMatch(JSON.stringify(own),/0405660106|tel:|wa\.me|周租|Wi-Fi|车位/);
 const lead=leadSchema.parse({name:'虚构验收',contact:'+447700900001',contactMethod:'phone',city:own.city,listingId:own.id,service:'selling',language:'zh',consent:true,requestId:crypto.randomUUID()});
 assert.equal(lead.city,'Gold Coast');
});
test('frozen com keeps its original layout and refuses an unexpected viewer when adding owner facts',()=>{
 const source=readFileSync('site/com/assets/index-Db9ODUdG.js','utf8');
 const result=saleListingComBundle(ownerListingsComBundle(source));
 assert.match(result,/kind=\$\{ne\}/);
 assert.match(result,/\["rent","sold","sale"\]/);
 assert.match(result,/出售中/);
 assert.match(result,/桉湾推荐/);
 assert.match(result,/S&&S\.kind==="sale"\?"sale":O/);
 assert.match(result,/挂牌出售中 \$\{/);
 assert.match(result,/成交记录 \$\{/);
 assert.match(result,/for sale/);
 assert.match(result,/sold records/);
 assert.match(result,/X!=="sold"&&p&&` · \$\{/);
 assert.equal(publicViewingListings('sale').length,1);
 assert.equal(publicViewingListings('sold').length,12);
 assert.ok(result.includes('facts:[...(X.features||[]).map(o)'));
 assert.equal((result.match(/className:/g)||[]).length,(source.match(/className:/g)||[]).length);
 assert.throws(()=>ownerListingsComBundle(source.replace('facts:O===','facts:unexpected===')),/Original com viewer changed/);
});
