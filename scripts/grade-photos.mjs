// Grade estate photographs for full-screen use: one consistent look, desktop 16:9 and phone 9:16 crops.
// Usage: node scripts/grade-photos.mjs <dir of high-resolution originals>
// Originals are named after the site file (taikoo-shing.jpg → public/img/hk/taikoo-shing.webp).
// Without an original, the existing site image is used and only the 1600px crop is written.
// The grade only adjusts tone, colour and sharpness; it never adds or removes anything in the picture.
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const SRC = process.argv[2];
const SITE = 'public/img/hk';
const OUT = 'public/img/hk/full';
const HAZY = new Set(['mid-levels', 'laguna-city', 'lei-king-wan', 'riviera-gardens', 'telford', 'city-garden', 'islands']);
const NIGHT = new Set(['harbour-night', 'kowloon']); // keep night scenes dark
const TARGET = 122; // mean luminance for daylight scenes

fs.mkdirSync(OUT, { recursive: true });
const names = fs.readdirSync(SITE).filter(f => f.endsWith('.webp')).map(f => f.replace('.webp', ''));
const report = [];
const large = [];
const usable = []; // wide enough to fill a screen

async function grade(input, name) {
  const base = sharp(input, { failOn: 'none' }).rotate();
  const { width = 0, height = 0 } = await base.metadata();
  // Measure first, then pull exposure towards the shared target.
  const stats = await sharp(input).rotate().resize(400).stats();
  const lum = stats.channels.slice(0, 3).reduce((a, c) => a + c.mean, 0) / 3;
  const contrast = stats.channels.slice(0, 3).reduce((a, c) => a + c.stdev, 0) / 3;
  // Local de-hazing only for flat, hazy pictures; crisp ones would turn into fake HDR.
  const hazy = !NIGHT.has(name) && (contrast < 62 || HAZY.has(name));
  const brightness = NIGHT.has(name) ? 1.04 : Math.min(1.15, Math.max(.9, TARGET / lum));
  const tile = Math.max(8, Math.round(Math.min(width, height) / 10));
  let pipeline = sharp(input, { failOn: 'none' }).rotate().normalise({ lower: 0.5, upper: 99.6 });
  if (hazy) pipeline = pipeline.clahe({ width: tile, height: tile, maxSlope: 2 });
  pipeline = pipeline.modulate({ brightness, saturation: NIGHT.has(name) ? 1.1 : 1.04 })
    .linear(1.02, -2)
    .sharpen({ sigma: .6, m1: .4, m2: 1 });
  return { buf: await pipeline.toBuffer(), width, height, lum: Math.round(lum), brightness, hazy };
}

for (const name of names) {
  const raw = SRC ? ['jpg', 'jpeg', 'png'].map(e => path.join(SRC, `${name}.${e}`)).find(p => fs.existsSync(p)) : null;
  const input = raw || path.join(SITE, `${name}.webp`);
  const g = await grade(input, name);
  const writes = [];
  const wide = (w, h, q) => sharp(g.buf).resize(w, h, { fit: 'cover', position: sharp.strategy.attention }).webp({ quality: q, effort: 5 }).toFile(path.join(OUT, `${name}-${w}.webp`));
  if (g.width >= 2200) { writes.push(wide(2560, 1440, 72)); large.push(name); }
  writes.push(wide(1600, 900, 76));
  if (g.width >= 1400) usable.push(name);
  // Portrait crop for phones; only when the source is tall enough to fill 1920 px without heavy upscaling.
  const tallH = Math.min(1920, Math.round(g.height));
  writes.push(sharp(g.buf).resize(Math.round(tallH * 9 / 16), tallH, { fit: 'cover', position: sharp.strategy.attention }).webp({ quality: 74, effort: 5 }).toFile(path.join(OUT, `${name}-tall.webp`)));
  await Promise.all(writes);
  report.push(`${name.padEnd(20)} ${raw ? 'original' : 'site    '} ${g.width}x${g.height} lum ${g.lum} ×${g.brightness.toFixed(2)}${g.width >= 2200 ? ' +2560' : ''}${g.hazy ? ' dehaze' : ''}`);
}
fs.writeFileSync('src/photo-full.ts', `/** Generated by scripts/grade-photos.mjs: graded full-screen crops in public/img/hk/full. */
export const FULL_PHOTOS = new Set(${JSON.stringify(usable)});
export const FULL_LARGE = new Set(${JSON.stringify(large)});
`);
console.log(report.join('\n'));
